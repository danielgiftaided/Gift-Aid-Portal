export type PostcodeLocation = {
  postcode_area: string | null
  postcode_district: string | null
  postcode_status: 'mapped' | 'missing' | 'invalid' | 'outside_uk'
}

export function postcodeLocation(value: unknown): PostcodeLocation {
  const empty = { postcode_area: null, postcode_district: null }
  if (typeof value !== 'string' || !value.trim()) return { ...empty, postcode_status: 'missing' }
  const postcode = value.toUpperCase().replace(/\s/g, '')
  const match = postcode.match(/^([A-Z]{1,2}\d[A-Z\d]?)(\d[A-Z]{2})$/)
  if (!match) return { ...empty, postcode_status: 'invalid' }
  const area = match[1].match(/^[A-Z]+/)![0]
  if (!Object.prototype.hasOwnProperty.call(POSTCODE_AREAS, area)) return { ...empty, postcode_status: 'outside_uk' }
  return { postcode_area: area, postcode_district: match[1], postcode_status: 'mapped' }
}
